def get_slot():
    tz = pytz.timezone("Europe/Kyiv")
    hour = datetime.now(tz).strftime("%H")
    return hour, TOPICS.get(hour, ("Перезагрузка", "Концентрация внимания, декомпозиция и ясность ума"))

def generate_via_rest(prompt, hour_key):
    """Прямой REST-запрос к Gemini без использования сторонних SDK."""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={GEMINI_KEY}"
    payload = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"maxOutputTokens": 600}
    }
    try:
        r = requests.post(url, json=payload, timeout=12)
        if r.status_code == 200:
            data = r.json()
            raw_text = data["candidates"][0]["content"]["parts"][0]["text"].strip()
            lines = raw_text.split("\n")
            title = lines[0].replace("*", "").replace("#", "").strip()
            body = "\n".join(lines[1:]).strip()
            return title, body
        else:
            print(f"Gemini API вернул статус {r.status_code}: {r.text}")
    except Exception as e:
        print(f"Сетевой запрос к Gemini API прерван ({e}). Задействуем резервный выпуск.")

    # Быстрый переход на готовую статью из блокнота
    fb_title, fb_body = FALLBACK_ARTICLES.get(hour_key, FALLBACK_ARTICLES["12"])
    return fb_title, fb_body

def main():
    if not CHAT_IDS or CHAT_IDS[0] == 123456789:
        raise ValueError("Укажите реальный числовой ID в переменной CHAT_IDS!")

    hour_key, (category, theme) = get_slot()
    prompt = (
        f"Ты — мудрый нейрокоуч. Напиши захватывающую, глубокую статью на тему: '{theme}'. "
        f"Категория выпуска: '{category}'. "
        "Стиль: живой, ясный, с метафорами нейробиологии и конкретной практикой в конце. "
        "Объем: 300-400 слов (на 10-15 минут вдумчивого чтения). "
        "Первая строка: только заголовок (без знаков # и звездочек). Далее: основной текст с абзацами."
    )

    title, body = generate_via_rest(prompt, hour_key)

    params = urllib.parse.urlencode({'cat': category, 'title': title, 'text': body})
    app_url = f"{VERCEL_URL}?{params}"

    safe_title = title.replace("<", "&lt;").replace(">", "&gt;")
    safe_cat = category.replace("<", "&lt;").replace(">", "&gt;")

    text_msg = (
        f"🔔 <b>Время перезагрузки ({safe_cat})</b>\n\n"
        f"<b>{safe_title}</b>\n\n"
        f"Новый 15-минутный выпуск готов к чтению."
    )
    keyboard = {
        "inline_keyboard": [[{"text": "📖 Открыть выпуск (~15 мин)", "web_app": {"url": app_url}}]]
    }

    for chat_id in CHAT_IDS:
        tg_url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
        payload = {
            "chat_id": chat_id,
            "text": text_msg,
            "parse_mode": "HTML",
            "reply_markup": keyboard
        }
        res = requests.post(tg_url, json=payload, timeout=10)
        print(f"Отправка на ID {chat_id}: код {res.status_code}, ответ: {res.text}")
        if res.status_code != 200:
            raise RuntimeError(f"Ошибка Telegram при доставке на ID {chat_id}: {res.text}")

if __name__ == "__main__":
    main()
