def get_slot():
    tz = pytz.timezone("Europe/Kyiv")
    hour = datetime.now(tz).strftime("%H")
    return hour, TOPICS.get(hour, ("Глубокая перезагрузка", "Нейропластичность, управление вниманием и системное мышление"))

def generate_via_rest(prompt):
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={GEMINI_KEY}"
    payload = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {
            "maxOutputTokens": 2048,
            "temperature": 0.7
        }
    }
    try:
        r = requests.post(url, json=payload, timeout=25)
        if r.status_code == 200:
            data = r.json()
            raw_text = data["candidates"][0]["content"]["parts"][0]["text"].strip()
            lines = raw_text.split("\n")
            title = lines[0].replace("*", "").replace("#", "").strip()
            body = "\n".join(lines[1:]).strip()
            return title, body
    except Exception as e:
        print(f"Сбой прямого запроса к API ({e}).")

    return None, None

